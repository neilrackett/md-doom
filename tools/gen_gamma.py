# tools/gen_gamma.py
#
# Generate rp/src/include/gamma.h: the sRGB transfer curve both ways,
# for doom_video.c's dither matching. A dither is two pens side by side,
# and the eye averages them as light, not as the 0..255 values: half
# black and half white looks like sRGB 188, not 128. So the mix a pair
# of pens can make is worked out in linear light and taken back to sRGB
# to compare with the colour it stands for.
#
#   gamma_lin[256]     sRGB 0..255 -> linear 0..4095
#   gamma_srgb[1024]   linear 0..4095, >> 2 -> sRGB 0..255
#
# `const`, so they live in flash. Run:
#   python3 tools/gen_gamma.py

OUT = "rp/src/include/gamma.h"


def to_lin(v):
    c = v / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def to_srgb(c):
    v = c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
    return min(255, max(0, round(v * 255)))


def rows(values, per_line, width):
    out = []
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join("%*d" % (width, v) for v in values[i:i + per_line]) + ",")
    return "\n".join(out)


lin = [round(to_lin(v) * 4095) for v in range(256)]
srgb = [to_srgb((i * 4 + 2) / 4095.0) for i in range(1024)]

with open(OUT, "w") as f:
    f.write("""/*
 * Copyright (C) 2026 Neil Rackett
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

/* Generated by tools/gen_gamma.py -- DO NOT EDIT.
 * The sRGB transfer curve both ways, for dither matching in linear
 * light: gamma_lin[v] is sRGB v (0..255) as linear 0..4095, and
 * gamma_srgb[l >> 2] takes linear l back to sRGB. `const` -> flash. */

#ifndef GAMMA_H_INCLUDED
#define GAMMA_H_INCLUDED

#include <stdint.h>

static const uint16_t gamma_lin[256] = {
%s
};

static const uint8_t gamma_srgb[1024] = {
%s
};

#endif /* GAMMA_H_INCLUDED */
""" % (rows(lin, 12, 4), rows(srgb, 16, 3)))
print("wrote", OUT)
